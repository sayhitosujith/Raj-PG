// Generates src/portalNeutral.css: the resident portal without any green. Every App.css rule that
// uses a green colour gets a copy scoped to .portal-shell, with each green swapped for a grey of the
// same lightness and opacity, so the owner's pages keep the brand green while residents see none.
// Run `npm run neutral-portal` after adding or changing green colours in App.css.
import { readFileSync, writeFileSync } from 'node:fs'
import postcss from 'postcss'

const source = new URL('../src/App.css', import.meta.url)
const target = new URL('../src/portalNeutral.css', import.meta.url)

// A colour is green when its hue is between yellow-green and cyan-green and it is tinted at all,
// however faintly: residents should see no green, so even near-white mints like #f7faf8 become a
// neutral grey of the same lightness.
function isGreen([r, g, b]) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b)
  if (max - min < 3) return false
  const d = max - min
  let hue = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  hue = (hue * 60 + 360) % 360
  return hue >= 75 && hue <= 185
}

// The grey with the same lightness (HSL), so text, tints and borders keep their contrast.
const toGrey = ([r, g, b]) => Math.round((Math.max(r, g, b) + Math.min(r, g, b)) / 2)

const hexPattern = /#([0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b/gi
const rgbPattern = /rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)/gi

function neutralise(value) {
  let changed = false
  let result = value.replace(hexPattern, (match, hex) => {
    const full = hex.length <= 4 ? [...hex].map((c) => c + c).join('') : hex
    const rgb = [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16))
    if (!isGreen(rgb)) return match
    changed = true
    const grey = toGrey(rgb).toString(16).padStart(2, '0')
    return `#${grey}${grey}${grey}${full.length === 8 ? full.slice(6) : ''}`
  })
  result = result.replace(rgbPattern, (match, r, g, b, alpha) => {
    const rgb = [r, g, b].map(Number)
    if (!isGreen(rgb)) return match
    changed = true
    const grey = toGrey(rgb)
    return alpha ? `rgb(${grey} ${grey} ${grey} / ${alpha})` : `rgb(${grey} ${grey} ${grey})`
  })
  return changed ? result : null
}

// The selector inside the portal: after a leading :root[...] (dark theme), otherwise in front.
function scope(selector) {
  if (selector.startsWith('.portal-shell')) return selector
  const root = selector.match(/^:root(\[[^\]]*\])*/)
  if (root) return root[0].length === selector.length ? `${selector} .portal-shell` : `${root[0]} .portal-shell${selector.slice(root[0].length)}`
  if (/^(html|body)\b/.test(selector)) return null
  return `.portal-shell ${selector}`
}

// Cards that keep their own colours in the portal: the notification settings (WhatsApp green, email
// blue, green switches) and Face ID sign-in. Their rules are not copied, so App.css applies as is.
const keepsColour = /\.(switch\b|whatsapp-|notification-preferences|passkey-)/

const input = postcss.parse(readFileSync(source, 'utf8'))
const output = postcss.root()
let ruleCount = 0

input.walkRules((rule) => {
  // Keyframes are global and cannot be scoped to the portal; none of them are visibly green here.
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return
  const declarations = []
  // Hand-written dark rules are copied whole, green or not: the dark sheet generated from this file
  // is scoped to .portal-shell, so it would otherwise outrank App.css's own dark rule for the element.
  const isDark = rule.selectors.some((selector) => selector.includes('[data-theme="dark"]'))
  rule.walkDecls((decl) => {
    // The brand colour itself is set by hand in App.css (near-black inside the portal), not greyed here.
    if (decl.prop === '--teal') return
    const value = neutralise(decl.value) ?? (isDark ? decl.value : null)
    if (value) declarations.push(postcss.decl({ prop: decl.prop, value, important: decl.important }))
  })
  if (!declarations.length) return
  const selectors = rule.selectors.filter((selector) => !keepsColour.test(selector)).map(scope).filter(Boolean)
  if (!selectors.length) return
  let node = postcss.rule({ selectors })
  declarations.forEach((decl) => node.append(decl))
  // Keep the rule's media/container/supports wrappers so it applies at the same sizes.
  for (let parent = rule.parent; parent && parent.type === 'atrule'; parent = parent.parent) {
    node = postcss.atRule({ name: parent.name, params: parent.params }).append(node)
  }
  output.append(node)
  ruleCount += 1
})

const header = `/* Generated by scripts/neutral-portal.mjs from App.css; do not edit by hand. The resident portal
   with every green colour replaced by a grey of the same lightness (${ruleCount} rules). Re-run
   \`npm run neutral-portal\` after changing green colours in App.css. */\n`
writeFileSync(target, header + output.toString() + '\n')
console.log(`portalNeutral.css: ${ruleCount} rules`)
